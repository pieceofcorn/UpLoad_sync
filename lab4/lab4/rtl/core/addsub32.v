timescale 1ns/1ps
module addsub32 (
    input  wire [31:0] A,
    input  wire [31:0] B,
    input  wire        SUB,
    output wire [31:0] F,
    output wire        CF,
    output wire        OF,
    output wire        SF,
    output wire        ZF
);
    wire [31:0] b_eff;
    wire c16;
    wire c32;
    wire [1:0] unused_group_g;
    wire [1:0] unused_group_p;

    // Two's-complement subtraction: A - B = A + (~B) + 1.
    // SUB=0 selects addition; SUB=1 inverts B and supplies carry-in 1.
    assign b_eff = B ^ {32{SUB}};

    // Low sixteen bits.
    cla16 u_low (
        .A(A[15:0]),
        .B(b_eff[15:0]),
        .C0(SUB),
        .S(F[15:0]),
        .C16(c16),
        .Gg(unused_group_g[0]),
        .Pg(unused_group_p[0])
    );

    // High sixteen bits use the carry generated by the low block.
    cla16 u_high (
        .A(A[31:16]),
        .B(b_eff[31:16]),
        .C0(c16),
        .S(F[31:16]),
        .C16(c32),
        .Gg(unused_group_g[1]),
        .Pg(unused_group_p[1])
    );

    // In addition CF is the carry-out. In subtraction it is the borrow
    // indicator, i.e. the inverse of the final two's-complement carry-out.
    assign CF = SUB ? ~c32 : c32;

    // Signed overflow occurs when A and the effective second operand have
    // equal signs but the result sign differs.
    assign OF = ~(A[31] ^ b_eff[31]) & (A[31] ^ F[31]);

    assign SF = F[31];
    assign ZF = (F == 32'b0);
endmodule
